using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Levee.Analyzers;

/// <summary>
/// In every roled project: the assembly's role attribute, and its handlers' registration. In a Host or Test project, the
/// composition root: the catalog of every operation it can see, and <c>AddLeveeOperations</c> registering the pipeline
/// and every handler. Missing, duplicate and malformed operations fail the build here.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class OperationGenerator : IIncrementalGenerator
{
    private static readonly SymbolDisplayFormat Global = SymbolDisplayFormat.FullyQualifiedFormat;

    /// <summary>For type arguments: keeps a result's <c>?</c>, which <c>typeof</c> can't take but a generic argument must.</summary>
    private static readonly SymbolDisplayFormat Argument =
        SymbolDisplayFormat.FullyQualifiedFormat.AddMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);
    private static readonly Regex OperationName = new("^[a-z][a-z0-9_]*(\\.[a-z][a-z0-9_]*)*$", RegexOptions.CultureInvariant);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var role = context.AnalyzerConfigOptionsProvider.Select((o, _) => Roles.Parse(Roles.Declared(o.GlobalOptions)));
        context.RegisterSourceOutput(context.CompilationProvider.Combine(role), (spc, pair) => Generate(spc, pair.Left, pair.Right));
    }

    private static void Generate(SourceProductionContext context, Compilation compilation, Role role)
    {
        if (role == Role.None || !Roles.UsesLevee(compilation))
        {
            return;
        }

        var own = AllTypes(compilation.Assembly.GlobalNamespace).ToList();
        var operations = own.Select(t => Operation(t, context, compilation)).Where(o => o is not null).Select(o => o!).ToList();
        var handlers = own.SelectMany(Handled).ToList();
        var processes = role is Role.Application or Role.Test ? own.SelectMany(Processed).ToList() : [];
        var helpers = role is Role.Application or Role.Test
            ? Helpers(handlers.Select(h => h.Handler).Concat(processes.Select(p => p.Process)), compilation.Assembly)
            : [];
        // A contract is Contracts'; the platform's own (internal) operations may sit with the application; a test declares its own.
        if (role is not (Role.Contracts or Role.Application or Role.Test or Role.TestSupport))
        {
            foreach (var op in operations)
            {
                context.ReportDiagnostic(Diagnostic.Create(Descriptors.MalformedOperation, op.Location, op.Type.ToDisplayString(),
                    $"an operation is declared in a {role} project. Fix: declare it in Contracts, or in Application if it's the platform's own (Internal = true)"));
            }
        }
        // An operation in Application is out of every client's sight (Contracts' catalog doesn't see it), so it may only be internal.
        foreach (var op in role == Role.Application ? operations.Where(o => !o.Internal) : [])
        {
            context.ReportDiagnostic(Diagnostic.Create(Descriptors.MalformedOperation, op.Location, op.Type.ToDisplayString(),
                "an operation in Application is the platform's own, never a client's. Fix: declare it Internal = true, or move it to Contracts"));
        }
        // A test's fakes are wired by the test itself; only one it marks [Adapter] is composed like an Adapter project's.
        var adapters = role switch
        {
            Role.Adapter => own.SelectMany(t => Adapted(t, context)).ToList(),
            Role.Test or Role.TestSupport => own.Where(Known.IsNamedAdapter).SelectMany(t => Adapted(t, context)).ToList(),
            _ => [],
        };
        var registration = "LeveeRegistration_" + Identifier(compilation.AssemblyName ?? "App");
        var registers = handlers.Count > 0 || adapters.Count > 0 || processes.Count > 0 || helpers.Count > 0;
        var refusals = Refusals(own, context);

        var source = new StringBuilder()
            .AppendLine("// <auto-generated/>")
            .AppendLine("#nullable enable")
            .AppendLine($"[assembly: global::Levee.LeveeRole({Literal(role.ToString())})]");
        foreach (var code in refusals)
        {
            source.AppendLine($"[assembly: global::Levee.LeveeRefuses({Literal(code)})]");
        }
        if (registers)
        {
            source.AppendLine($"[assembly: global::Levee.LeveeRegistration(typeof(global::Levee.Generated.{registration}))]");
            foreach (var h in handlers)
            {
                source.AppendLine($"[assembly: global::Levee.LeveeHandles(typeof({h.Operation.ToDisplayString(Global)}))]");
            }
            foreach (var a in adapters)
            {
                source.AppendLine($"[assembly: global::Levee.LeveeAdapts(typeof({a.Port.ToDisplayString(Global)}), {(a.Name is null ? "null" : Literal(a.Name))}, (global::Levee.AdapterLifetime){a.Lifetime})]");
            }
            source.AppendLine()
                .AppendLine("namespace Levee.Generated")
                .AppendLine("{")
                .AppendLine("    /// <summary>This assembly's handlers and adapters, for the composition root to register.</summary>")
                .AppendLine("    [global::System.CodeDom.Compiler.GeneratedCode(\"Levee\", \"0.0.1\")]")
                .AppendLine("    [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]")
                .AppendLine($"    public static class {registration}")
                .AppendLine("    {")
                .AppendLine("        /// <summary>Registers every handler, and every adapter but those a port's setting in <paramref name=\"configuration\"/> didn't choose.</summary>")
                .AppendLine("        /// <param name=\"services\">The composition root's services.</param>")
                .AppendLine("        /// <param name=\"configuration\">The settings that choose adapters; without them, every adapter is registered.</param>")
                .AppendLine("        public static void Register(global::Microsoft.Extensions.DependencyInjection.IServiceCollection services,")
                .AppendLine("            global::Microsoft.Extensions.Configuration.IConfiguration? configuration = null)")
                .AppendLine("        {");
            foreach (var h in handlers)
            {
                var contract = h.Streams ? "ISubscriptionHandler" : "IOperationHandler";
                source.AppendLine("            global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions.AddScoped<"
                    + $"global::Levee.{contract}<{h.Operation.ToDisplayString(Global)}, {h.Result.ToDisplayString(Argument)}>, {h.Handler.ToDisplayString(Global)}>(services);");
            }
            foreach (var helper in helpers)
            {
                source.AppendLine("            global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions.TryAddScoped<"
                    + $"{helper.ToDisplayString(Global)}>(services);");
            }
            foreach (var (process, input) in processes)
            {
                source.AppendLine("            global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions.AddScoped<"
                    + $"global::Levee.IProcess<{input.ToDisplayString(Global)}>, {process.ToDisplayString(Global)}>(services);");
            }
            const string Di = "global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions";
            const string Resolve = "global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService";
            // One instance per adapter, however many ports it serves: its ports resolve to it, not to copies of it.
            // An adapter its port's setting didn't choose isn't registered: its dependencies needn't resolve where it isn't used.
            static string? Chosen(AdapterModel a) =>
                a.Name is not null && !Known.IsMany(a.Port) && Known.SelectedBy(a.Port) is { Length: > 0 } setting
                    ? Known.DefaultAdapter(a.Port) is { } fallback
                        ? $"global::Levee.PortSelection.Wants(configuration, {Literal(setting)}, {Literal(a.Name)}, {Literal(fallback)})"
                        : $"global::Levee.PortSelection.Wants(configuration, {Literal(setting)}, {Literal(a.Name)})"
                    : null;
            foreach (var adapter in adapters.GroupBy(a => a.Adapter, SymbolEqualityComparer.Default))
            {
                var first = adapter.First();
                var type = first.Adapter.ToDisplayString(Global);
                var lifetime = first.Lifetime switch { 1 => "Singleton", 2 => "Transient", _ => "Scoped" };
                var conditions = adapter.Select(Chosen).ToList();
                var indent = "            ";
                if (conditions.All(c => c is not null))
                {
                    source.AppendLine($"            if ({string.Join(" || ", conditions)})").AppendLine("            {");
                    indent = "                ";
                }
                source.AppendLine($"{indent}{Di}.Add{lifetime}<{type}>(services);");
                foreach (var a in adapter)
                {
                    var port = a.Port.ToDisplayString(Global);
                    if (a.Name is null || Known.IsMany(a.Port))
                    {
                        source.AppendLine($"{indent}{Di}.Add{lifetime}<{port}>(services, static provider => {Resolve}<{type}>(provider));");
                    }
                    if (a.Name is not null)
                    {
                        var keyed = $"{Di}.AddKeyed{lifetime}<{port}>(services, {Literal(a.Name)}, static (provider, _) => {Resolve}<{type}>(provider));";
                        source.AppendLine(Chosen(a) is { } wants && indent.Length == 12 ? $"{indent}if ({wants}) {keyed}" : $"{indent}{keyed}");
                    }
                }
                if (indent.Length > 12)
                {
                    source.AppendLine("            }");
                }
            }
            source.AppendLine("        }").AppendLine("    }").AppendLine("}");
        }
        context.AddSource("Levee.Assembly.g.cs", source.ToString());

        // The composition root is the Composition project when there is one, which every Host shares; else the Host (or a test) itself.
        // A process that sees no application (it only calls one, through an SDK) has nothing to compose.
        var referencedRoles = compilation.SourceModule.ReferencedAssemblySymbols.Select(Roles.Of).ToList();
        var composed = referencedRoles.Contains(Role.Composition);
        var application = referencedRoles.Contains(Role.Application) || handlers.Count > 0 || operations.Count > 0;
        if (role == Role.Composition || (role is Role.Host or Role.Tool or Role.Test && !composed && application))
        {
            Compose(context, compilation, role, operations, handlers, adapters, registers ? registration : null, refusals);
            DuplicateProcesses(context, compilation, processes, ownOnly: false);
        }
        else if (role == Role.Test && composed && registers)
        {
            ComposeTestPart(context, compilation, operations, handlers, registration);
            DuplicateProcesses(context, compilation, processes, ownOnly: true);
        }
        if (role == Role.Contracts && operations.Any(o => !o.Internal))
        {
            CatalogContracts(context, compilation, operations);
        }
    }

    /// <summary>The codes this assembly's access policies and admissions declare they refuse with, each checked for shape.</summary>
    private static List<string> Refusals(List<INamedTypeSymbol> own, SourceProductionContext context)
    {
        var codes = new List<string>();
        foreach (var type in own.Where(t => t.AllInterfaces.Any(i => i.ToDisplayString() is "Levee.IAccessPolicy" or "Levee.IAdmission")))
        {
            var declared = type.GetAttributes().FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == "Levee.RefusesAttribute");
            foreach (var code in declared?.ConstructorArguments.SelectMany(a => a.Kind == TypedConstantKind.Array ? a.Values : [a]).Select(v => v.Value as string ?? "") ?? [])
            {
                if (!OperationName.IsMatch(code))
                {
                    context.ReportDiagnostic(Diagnostic.Create(Descriptors.MalformedOperation, type.Locations.FirstOrDefault() ?? Location.None, type.ToDisplayString(),
                        $"refusal code '{code}' isn't lowercase snake_case segments joined by dots. Fix: name it <area>.<reason>, like access.tenant"));
                    continue;
                }
                codes.Add(code);
            }
        }
        return codes;
    }

    /// <summary>
    /// What a client may call, in the project that declares it: the CLI, MCP and an app's own checks read the contract by
    /// name, offline, without the application or its composition. Named for the assembly, so a client of several sees each.
    /// </summary>
    private static void CatalogContracts(SourceProductionContext context, Compilation compilation, List<OperationModel> operations)
    {
        var ns = string.Join(".", (compilation.AssemblyName ?? "App").Split('.').Select(p => Identifier(p)).Select(p => char.IsDigit(p[0]) ? "_" + p : p));
        var source = new StringBuilder()
            .AppendLine("// <auto-generated/>")
            .AppendLine("#nullable enable")
            .AppendLine($"namespace {ns}")
            .AppendLine("{")
            .AppendLine("    /// <summary>The contract this project declares, for clients: no handlers, nothing internal.</summary>")
            .AppendLine("    [global::System.CodeDom.Compiler.GeneratedCode(\"Levee\", \"0.0.1\")]")
            .AppendLine("    public static class LeveeCatalog")
            .AppendLine("    {")
            .AppendLine("        /// <summary>Every operation this project declares that a client may call: internal ones aren't.</summary>")
            .AppendLine("        public static global::Levee.OperationCatalog Catalog { get; } = new global::Levee.OperationCatalog(new global::Levee.OperationDescriptor[]")
            .AppendLine("        {");
        foreach (var op in operations.Where(o => !o.Internal).OrderBy(o => o.Name, StringComparer.Ordinal))
        {
            source.AppendLine($"            {DescriptorOf(op)},");
        }
        source.AppendLine("        });").AppendLine("    }").AppendLine("}");
        context.AddSource("Levee.Contracts.g.cs", source.ToString());
    }

    private static void Compose(SourceProductionContext context, Compilation compilation, Role role, List<OperationModel> own, List<HandlerModel> ownHandlers,
        List<AdapterModel> ownAdapters, string? ownRegistration, List<string> ownRefusals)
    {
        var referenced = compilation.SourceModule.ReferencedAssemblySymbols.Where(a => Roles.Of(a) != Role.None).ToList();
        var refusals = ownRefusals.Concat(referenced.SelectMany(a => a.GetAttributes())
                .Where(a => a.AttributeClass?.ToDisplayString() == "Levee.LeveeRefusesAttribute")
                .Select(a => a.ConstructorArguments.FirstOrDefault().Value as string)
                .OfType<string>())
            .Distinct(StringComparer.Ordinal).OrderBy(c => c, StringComparer.Ordinal).ToList();
        // A referenced operation's shape was checked where it's declared, from its source, and is checked again by the catalog at
        // start; metadata here hides its private members, so it isn't judged again from it. What else fails here is reported, never
        // left out of the catalog.
        var operations = own.Concat(referenced.SelectMany(a => AllTypes(a.GlobalNamespace))
                .Where(t => t.DeclaredAccessibility == Accessibility.Public)
                .Select(t => Operation(t, context, compilation: null))
                .Where(o => o is not null)
                .Select(o => o!))
            .ToList();

        var handled = ownHandlers.Select(h => h.Operation)
            .Concat(referenced.SelectMany(a => a.GetAttributes())
                .Where(a => a.AttributeClass?.ToDisplayString() == Known.HandlesAttribute)
                .Select(a => a.ConstructorArguments.FirstOrDefault().Value as INamedTypeSymbol)
                .Where(t => t is not null)
                .Select(t => t!))
            .ToList();

        var registrations = referenced.SelectMany(a => a.GetAttributes())
            .Where(a => a.AttributeClass?.ToDisplayString() == Known.RegistrationAttribute)
            .Select(a => (a.ConstructorArguments.FirstOrDefault().Value as INamedTypeSymbol)?.ToDisplayString(Global))
            .Where(r => r is not null)
            .Select(r => r!)
            .Concat(ownRegistration is null ? [] : [$"global::Levee.Generated.{ownRegistration}"])
            .OrderBy(r => r, StringComparer.Ordinal)
            .ToList();

        foreach (var op in operations)
        {
            var count = handled.Count(h => SymbolEqualityComparer.Default.Equals(h, op.Type));
            if (count != 1)
            {
                context.ReportDiagnostic(count == 0
                    ? Diagnostic.Create(Descriptors.MissingHandler, op.Location, op.Name, op.Type.ToDisplayString())
                    : Diagnostic.Create(Descriptors.DuplicateHandler, op.Location, op.Name, op.Type.ToDisplayString(), count));
            }
        }
        foreach (var group in operations.GroupBy(o => o.Name, StringComparer.Ordinal).Where(g => g.Count() > 1))
        {
            context.ReportDiagnostic(Diagnostic.Create(Descriptors.DuplicateName, group.First().Location, group.Key,
                string.Join(", ", group.Select(o => o.Type.ToDisplayString()))));
        }
        // Written even when a check failed, so the build reports that check alone, not the composition it would have produced.
        var bindings = Bind(context, compilation, role, referenced, ownAdapters, out var routed);
        operations = [.. operations.GroupBy(o => o.Name, StringComparer.Ordinal).Select(g => g.First())];

        var source = new StringBuilder()
            .AppendLine("// <auto-generated/>")
            .AppendLine("#nullable enable")
            .AppendLine("namespace Levee.Generated")
            .AppendLine("{")
            .AppendLine("    /// <summary>The app's composition: its catalog, and the registration every host shares.</summary>")
            .AppendLine("    [global::System.CodeDom.Compiler.GeneratedCode(\"Levee\", \"0.0.1\")]")
            .AppendLine($"    {(role == Role.Composition ? "public" : "internal")} static class LeveeComposition")
            .AppendLine("    {")
            .AppendLine("        /// <summary>Every operation this host can see.</summary>")
            .AppendLine("        public static global::Levee.OperationCatalog Catalog { get; } = new global::Levee.OperationCatalog(new global::Levee.OperationDescriptor[]")
            .AppendLine("        {");
        foreach (var op in operations.OrderBy(o => o.Name, StringComparer.Ordinal))
        {
            source.AppendLine($"            {DescriptorOf(op)},");
        }
        source.AppendLine(refusals.Count == 0 ? "        });" : $"        }}, refusals: new string[] {{ {string.Join(", ", refusals.Select(Literal))} }});")
            .AppendLine()
            .AppendLine("        /// <summary>")
            .AppendLine("        /// The pipeline over <see cref=\"Catalog\"/>, every handler and adapter, and each port bound: to its one adapter, or to the")
            .AppendLine("        /// one its setting in <paramref name=\"configuration\"/> names (checked here, so a bad setting fails at startup).")
            .AppendLine("        /// </summary>")
            .AppendLine("        /// <param name=\"services\">The host's services.</param>")
            .AppendLine("        /// <param name=\"configuration\">The settings that choose adapters.</param>")
            .AppendLine("        /// <param name=\"configure\">Levee's options.</param>")
            .AppendLine("        /// <returns><paramref name=\"services\"/>.</returns>")
            .AppendLine("        public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection AddLeveeOperations(")
            .AppendLine("            this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services,")
            .AppendLine("            global::Microsoft.Extensions.Configuration.IConfiguration? configuration = null,")
            .AppendLine("            global::System.Action<global::Levee.LeveeOptions>? configure = null)")
            .AppendLine("        {")
            .AppendLine("            global::Levee.LeveeServiceCollectionExtensions.AddLevee(services, Catalog, configure);");
        foreach (var r in registrations)
        {
            source.AppendLine($"            {r}.Register(services, configuration);");
        }
        foreach (var (port, setting, adapters) in bindings)
        {
            var type = port.ToDisplayString(Global);
            var local = "selected_" + Identifier(port.ToDisplayString());
            var lifetimes = string.Join(" ", adapters.Select(a => $"{Literal(a.Name)} => (global::Levee.AdapterLifetime){a.Lifetime},"));
            var fallback = Known.DefaultAdapter(port) is { } name ? $", {Literal(name)}" : "";
            source.AppendLine($"            var {local} = global::Levee.PortSelection.Select(configuration, {Literal(setting)}, {Literal(port.ToDisplayString())}, new[] {{ {string.Join(", ", adapters.Select(a => Literal(a.Name)))} }}{fallback});")
                .AppendLine($"            global::Levee.PortSelection.Bind<{type}>(services, {local}, {local} switch {{ {lifetimes} _ => global::Levee.AdapterLifetime.Scoped }});");
        }
        foreach (var (port, names, singleton) in routed)
        {
            var type = port.ToDisplayString(Global);
            // As long-lived as its adapters allow: a singleton router may take a set of singletons.
            source.AppendLine($"            global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions.Add{(singleton ? "Singleton" : "Scoped")}<global::Levee.IAdapters<{type}>>(services, "
                + $"provider => new global::Levee.Adapters<{type}>(provider, new[] {{ {string.Join(", ", names.Select(Literal))} }}));");
        }
        source.AppendLine("            return services;").AppendLine("        }").AppendLine("    }").AppendLine("}");
        context.AddSource("Levee.Composition.g.cs", source.ToString());
    }

    /// <summary>
    /// A queued job names its input's type alone, and the worker resolves the one <c>IProcess&lt;TInput&gt;</c> for it, so two
    /// for one input leave which runs to registration order. Across the root's own and every Application it references; a
    /// test part reports only where its own process is one of them, as the app's root reported the rest.
    /// </summary>
    private static void DuplicateProcesses(SourceProductionContext context, Compilation compilation, List<(INamedTypeSymbol Process, ITypeSymbol Input)> own, bool ownOnly)
    {
        var all = own.Concat(compilation.SourceModule.ReferencedAssemblySymbols.Where(a => Roles.Of(a) == Role.Application)
            .SelectMany(a => AllTypes(a.GlobalNamespace)).SelectMany(Processed));
        foreach (var group in all.GroupBy(p => p.Input, SymbolEqualityComparer.Default).Where(g => g.Count() > 1))
        {
            var mine = group.FirstOrDefault(p => own.Contains(p));
            if (ownOnly && mine.Process is null)
            {
                continue;
            }
            context.ReportDiagnostic(Diagnostic.Create(Descriptors.DuplicateProcess, mine.Process?.Locations.FirstOrDefault() ?? Location.None,
                group.Key!.ToDisplayString(), group.Count(), string.Join(", ", group.Select(p => p.Process.ToDisplayString()))));
        }
    }

    private static string DescriptorOf(OperationModel op)
    {
        var types = $"{op.Type.ToDisplayString(Global)}, {op.Result.ToDisplayString(Argument)}";
        var flags = $"{(op.Platform ? "true" : "false")}, {(op.Internal ? "true" : "false")}"
            + (op.Metadata.Count == 0 ? "" : $", metadata: new global::System.Attribute[] {{ {string.Join(", ", op.Metadata)} }}")
            + (op.Errors.Count == 0 || op.Streams ? "" : $", errors: new string[] {{ {string.Join(", ", op.Errors.Select(Literal))} }}")
            + (op.CallerScoped ? ", callerScoped: true" : "")
            + (op.Unscoped ? ", unscoped: true" : "");
        return op.Streams
            ? $"global::Levee.OperationDescriptor.CreateSubscription<{types}>({Literal(op.Name)}, {Literal(op.Summary)}, {Literal(op.Access)}, {flags})"
            : $"global::Levee.OperationDescriptor.Create<{types}>({Literal(op.Name)}, {Literal(op.Summary)}, {Literal(op.Access)}, "
                + $"(global::Levee.Effects){op.Effects}, (global::Levee.Idempotency){op.Idempotency}, {flags})";
    }

    /// <summary>
    /// A test over an app with a Composition project: its own operations and handlers, added on top of the app's catalog
    /// (<c>AddLeveeTestOperations</c> after the composition's <c>AddLeveeOperations</c>).
    /// </summary>
    private static void ComposeTestPart(SourceProductionContext context, Compilation compilation, List<OperationModel> own, List<HandlerModel> ownHandlers,
        string? ownRegistration)
    {
        var handled = ownHandlers.Select(h => h.Operation)
            .Concat(compilation.SourceModule.ReferencedAssemblySymbols.SelectMany(a => a.GetAttributes())
                .Where(a => a.AttributeClass?.ToDisplayString() == Known.HandlesAttribute)
                .Select(a => a.ConstructorArguments.FirstOrDefault().Value as INamedTypeSymbol)
                .Where(t => t is not null)
                .Select(t => t!))
            .ToList();
        foreach (var op in own)
        {
            var count = handled.Count(h => SymbolEqualityComparer.Default.Equals(h, op.Type));
            if (count != 1)
            {
                context.ReportDiagnostic(count == 0
                    ? Diagnostic.Create(Descriptors.MissingHandler, op.Location, op.Name, op.Type.ToDisplayString())
                    : Diagnostic.Create(Descriptors.DuplicateHandler, op.Location, op.Name, op.Type.ToDisplayString(), count));
            }
        }
        // A test's handler for the app's own operation would quietly replace the app's at run time.
        foreach (var h in ownHandlers.Where(h => !own.Any(o => SymbolEqualityComparer.Default.Equals(o.Type, h.Operation))))
        {
            context.ReportDiagnostic(Diagnostic.Create(Descriptors.DuplicateHandler, h.Handler.Locations.FirstOrDefault() ?? Location.None,
                h.Operation.Name, h.Operation.ToDisplayString(), 2));
        }
        var source = new StringBuilder()
            .AppendLine("// <auto-generated/>")
            .AppendLine("#nullable enable")
            .AppendLine("namespace Levee.Generated")
            .AppendLine("{")
            .AppendLine("    [global::System.CodeDom.Compiler.GeneratedCode(\"Levee\", \"0.0.1\")]")
            .AppendLine("    internal static class LeveeTestComposition")
            .AppendLine("    {")
            .AppendLine("        /// <summary>This test's own operations.</summary>")
            .AppendLine("        public static global::Levee.OperationDescriptor[] Operations { get; } = new global::Levee.OperationDescriptor[]")
            .AppendLine("        {");
        foreach (var op in own.OrderBy(o => o.Name, StringComparer.Ordinal))
        {
            source.AppendLine($"            {DescriptorOf(op)},");
        }
        source.AppendLine("        };")
            .AppendLine()
            .AppendLine("        /// <summary>This test's operations, handlers and adapters, on top of the app's composition.</summary>")
            .AppendLine("        public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection AddLeveeTestOperations(")
            .AppendLine("            this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)")
            .AppendLine("        {")
            .AppendLine("            global::Levee.LeveeServiceCollectionExtensions.AddLeveePart(services, Operations);");
        if (ownRegistration is not null)
        {
            source.AppendLine($"            global::Levee.Generated.{ownRegistration}.Register(services);");
        }
        source.AppendLine("            return services;").AppendLine("        }").AppendLine("    }").AppendLine("}");
        context.AddSource("Levee.TestComposition.g.cs", source.ToString());
    }

    /// <summary>The operation <paramref name="type"/> declares, or null. With a context, reports what's malformed about it.</summary>
    /// <param name="compilation">The compilation declaring <paramref name="type"/>, whose source its contract's shape is judged from; null
    /// for an operation a referenced assembly declares, judged there.</param>
    private static OperationModel? Operation(INamedTypeSymbol type, SourceProductionContext? context, Compilation? compilation)
    {
        var attribute = type.GetAttributes().FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == Known.OperationAttribute);
        var contract = type.AllInterfaces.FirstOrDefault(i => Known.Is(i, "IOperation", 1) || Known.Is(i, "ISubscription", 1));
        var streams = contract is not null && Known.Is(contract, "ISubscription", 1);
        if (attribute is null && contract is null)
        {
            return null;
        }

        var location = type.Locations.FirstOrDefault() ?? Location.None;
        void Report(string problem) =>
            context?.ReportDiagnostic(Diagnostic.Create(Descriptors.MalformedOperation, location, type.ToDisplayString(), problem));

        if (type.TypeKind != TypeKind.Class || type.IsAbstract || type.IsGenericType)
        {
            if (attribute is not null || !type.IsAbstract)
            {
                Report("an operation is a non-generic, non-abstract class or record. Fix: declare it as a public sealed record");
            }
            return null;
        }
        if (attribute is null || contract is null)
        {
            Report("an operation needs both [Operation(name, access)] and IOperation<TResult> (or ISubscription<TItem>). Fix: add the one it lacks; dotnet levee generate operation writes the whole shape");
            return null;
        }
        if (!type.IsSealed)
        {
            Report("an operation is sealed, so no subclass carries more than its contract. Fix: declare it a public sealed record");
            return null;
        }
        if (compilation is not null && Untyped(type, new HashSet<ITypeSymbol>(SymbolEqualityComparer.Default), "") is { } untyped)
        {
            Report($"its input's {untyped} is untyped, so its schema, redaction and the strict wire can't see what it holds. Fix: give it a type of its own");
            return null;
        }
        foreach (var (what, walked) in new[] { ("input", (ITypeSymbol)type), ("result", contract.TypeArguments[0]) })
        {
            if (compilation is not null && Shapeless(walked, new HashSet<ITypeSymbol>(SymbolEqualityComparer.Default), "", what == "input", compilation) is { } shapeless)
            {
                Report($"its {what}'s {shapeless.Path} {shapeless.Problem}");
                return null;
            }
        }
        if (type.DeclaredAccessibility != Accessibility.Public || type.ContainingType is not null)
        {
            Report("an operation is a public top-level type, so every host can catalog it. Fix: make it public and move it out of its containing type");
            return null;
        }

        var name = attribute.ConstructorArguments.ElementAtOrDefault(0).Value as string ?? "";
        var access = attribute.ConstructorArguments.ElementAtOrDefault(1).Value as string ?? "";
        if (!OperationName.IsMatch(name))
        {
            Report($"name '{name}' isn't lowercase snake_case segments joined by dots. Fix: name it <area>.<verb> or <area>.<noun>.<verb>, like notes.create or billing.invoice_lines.list");
            return null;
        }
        if (string.IsNullOrWhiteSpace(access))
        {
            Report("access is empty. Fix: name what the caller needs in the app's own vocabulary (member, admin, platform-admin); the app's IAccessPolicy decides it");
            return null;
        }

        var named = attribute.NamedArguments.Where(a => a.Value.Kind != TypedConstantKind.Array).ToDictionary(a => a.Key, a => a.Value.Value);
        var effects = named.TryGetValue("Effects", out var e) && e is int ei ? ei : 1;
        var idempotency = named.TryGetValue("Idempotency", out var i) && i is int ii ? ii : 0;
        var summary = named.TryGetValue("Summary", out var s) && s is string ss ? ss : "";
        var platform = named.TryGetValue("Platform", out var pl) && pl is true;
        var @internal = named.TryGetValue("Internal", out var it) && it is true;
        var callerScoped = named.TryGetValue("CallerScoped", out var cs) && cs is true;
        var unscoped = named.TryGetValue("Unscoped", out var un) && un is true;
        var metadata = type.GetAttributes()
            .Where(a => a.AttributeClass?.GetAttributes().Any(m => m.AttributeClass?.ToDisplayString() == Known.MetadataAttribute) == true)
            .Select(Construct)
            .ToList();
        var errors = attribute.NamedArguments.FirstOrDefault(a => a.Key == "Errors").Value is { Kind: TypedConstantKind.Array } declared
            ? declared.Values.Select(v => v.Value as string ?? "").ToList()
            : [];
        if (errors.FirstOrDefault(c => !OperationName.IsMatch(c)) is { } badCode)
        {
            Report($"error code '{badCode}' isn't lowercase snake_case segments joined by dots. Fix: name it <area>.<reason>, like notes.too_long");
            return null;
        }
        if (streams && errors.Count > 0)
        {
            Report("a subscription declares no error codes of its handler's: it's refused as it opens, or ended on a recheck, by the access policy's and admissions' own codes, and by Levee's when it fails. Fix: remove Errors");
            return null;
        }
        if (streams && (effects != 1 || idempotency != 0))
        {
            Report("a subscription only reads, and holds nothing to repeat. Fix: leave Effects and Idempotency unset; a write is its own operation");
            return null;
        }
        if (streams && SecretIn(type, new HashSet<ITypeSymbol>(SymbolEqualityComparer.Default), "") is { } secret)
        {
            Report($"its input's {secret} is a [Secret], but a subscription's input travels in its URL, which proxies and access logs keep. Fix: pass a reference to the secret, or open the stream with an operation that takes it in its body");
            return null;
        }
        if ((effects & ~1) != 0 && idempotency == 0)
        {
            context?.ReportDiagnostic(Diagnostic.Create(Descriptors.WriteIdempotency, location, name, EffectsText(effects)));
        }
        var scoped = type.AllInterfaces.Any(i => Known.Is(i, "IScopedOperation", 0));
        var scopes = (scoped ? 1 : 0) + (platform ? 1 : 0) + (callerScoped ? 1 : 0) + (unscoped ? 1 : 0);
        if (scopes != 1)
        {
            context?.ReportDiagnostic(Diagnostic.Create(Descriptors.ScopeUndeclared, location, name,
                scopes == 0 ? "doesn't say whose rows it may see" : "declares more than one scope"));
        }

        return new OperationModel(type, contract.TypeArguments[0], name, access, summary, effects, idempotency, platform, @internal, streams, metadata,
            errors, callerScoped, unscoped, location);
    }

    /// <summary>
    /// Every port the composition sees, checked against its adapters. In a Host every port must be bound; a test or a Tool
    /// binds what it references. Returns the ports a setting chooses between, to bind at startup.
    /// </summary>
    private static List<(INamedTypeSymbol Port, string Setting, (string Name, int Lifetime)[] Adapters)> Bind(SourceProductionContext context, Compilation compilation, Role role,
        List<IAssemblySymbol> referenced, List<AdapterModel> ownAdapters, out List<(INamedTypeSymbol Port, string[] Names, bool Singleton)> routed)
    {
        var ports = AllTypes(compilation.Assembly.GlobalNamespace)
            .Concat(referenced.Where(a => Roles.Of(a) == Role.Application).SelectMany(a => AllTypes(a.GlobalNamespace)).Where(t => t.DeclaredAccessibility == Accessibility.Public))
            .Where(Known.IsPort)
            .Distinct<INamedTypeSymbol>(SymbolEqualityComparer.Default)
            .ToList();
        var adapts = ownAdapters.Select(a => (Port: (INamedTypeSymbol)a.Port, a.Name, a.Lifetime))
            .Concat(referenced.SelectMany(a => a.GetAttributes())
                .Where(a => a.AttributeClass?.ToDisplayString() == Known.AdaptsAttribute)
                .Where(a => a.ConstructorArguments.Length == 3 && a.ConstructorArguments[0].Value is INamedTypeSymbol)
                .Select(a => (Port: (INamedTypeSymbol)a.ConstructorArguments[0].Value!, Name: a.ConstructorArguments[1].Value as string,
                    Lifetime: a.ConstructorArguments[2].Value is int l ? l : 0)))
            .ToList();

        var bindings = new List<(INamedTypeSymbol, string, (string Name, int Lifetime)[])>();
        routed = [];
        foreach (var port in ports.OrderBy(p => p.ToDisplayString(), StringComparer.Ordinal))
        {
            var mine = adapts.Where(a => SymbolEqualityComparer.Default.Equals(a.Port, port)).ToList();
            var location = port.Locations.FirstOrDefault(l => l.IsInSource) ?? Location.None;
            var setting = Known.SelectedBy(port);
            string? problem = null;
            if (Known.IsMany(port))
            {
                var named = mine.Where(a => a.Name is not null).ToList();
                problem = setting is not null ? "a set (Many) is served by every adapter, so no setting chooses one. Fix: remove SelectedBy, or drop Many if one adapter serves at a time"
                    : Known.DefaultAdapter(port) is { } fallback ? $"a set (Many) is served by every adapter, so there's no one adapter for Default '{fallback}' to stand in for. Fix: remove Default, or drop Many and add SelectedBy if one adapter serves at a time"
                    : named.Count > 0 && named.Count < mine.Count ? "a routed set names every adapter, or none. Fix: name each [Adapter(\"...\")], or none of them"
                    : named.GroupBy(a => a.Name, StringComparer.Ordinal).FirstOrDefault(g => g.Count() > 1) is { } twice ? $"two adapters are named '{twice.Key}'. Fix: give each a distinct name"
                    : null;
                if (problem is not null)
                {
                    context.ReportDiagnostic(Diagnostic.Create(Descriptors.PortBinding, location, port.ToDisplayString(), problem));
                }
                else if (named.Count > 0)
                {
                    routed.Add((port, named.Select(a => a.Name!).OrderBy(n => n, StringComparer.Ordinal).ToArray(), named.All(a => a.Lifetime == 1)));
                }
                continue;
            }
            if (mine.Count == 0)
            {
                // A Tool (a migrator, the role bootstrap) binds what it references, as a test does: its operations are few, and
                // one that needs an unbound port fails at its first resolution, naming the port.
                if (role is Role.Host or Role.Composition)
                {
                        context.ReportDiagnostic(Diagnostic.Create(Descriptors.UnboundPort, location, port.ToDisplayString()));
                }
                continue;
            }
            if (setting is null && Known.DefaultAdapter(port) is not null)
            {
                problem = "it has a Default but no SelectedBy, so there's no setting for it to stand in for. Fix: add [Port(SelectedBy = \"Section:Key\")], or drop Default";
            }
            else if (setting is null)
            {
                problem = mine.Count > 1 ? $"{mine.Count} adapters, and nothing chooses between them. Fix: add [Port(SelectedBy = \"Section:Key\")] and name each [Adapter(\"...\")]; if all serve at once, declare [Port(Many = true)]"
                    : mine[0].Name is { } named ? $"its adapter is named '{named}', but no setting chooses it. Fix: add [Port(SelectedBy = \"Section:Key\")], or drop the name if it's the only adapter there will be" : null;
            }
            else if (string.IsNullOrWhiteSpace(setting))
            {
                problem = "SelectedBy is empty. Fix: name the configuration key that chooses the adapter, like Providers:HomePrices";
            }
            else if (mine.Any(a => string.IsNullOrWhiteSpace(a.Name)))
            {
                problem = $"{setting} chooses its adapter, so each needs a name. Fix: name every adapter, [Adapter(\"...\")], with the value {setting} takes";
            }
            else if (mine.GroupBy(a => a.Name, StringComparer.Ordinal).FirstOrDefault(g => g.Count() > 1) is { } twice)
            {
                problem = $"two adapters are named '{twice.Key}'. Fix: give each a distinct name";
            }
            else if (Known.DefaultAdapter(port) is { } fallback && !mine.Any(a => a.Name == fallback))
            {
                problem = $"its Default '{fallback}' names no adapter. Fix: name one of {string.Join(", ", mine.Select(a => $"'{a.Name}'"))}, or add the adapter it names";
            }
            if (problem is not null)
            {
                context.ReportDiagnostic(Diagnostic.Create(Descriptors.PortBinding, location, port.ToDisplayString(), problem));
            }
            else if (setting is not null)
            {
                bindings.Add((port, setting, mine.Select(a => (a.Name!, a.Lifetime)).OrderBy(n => n.Item1, StringComparer.Ordinal).ToArray()));
            }
        }
        return bindings;
    }

    private static readonly HashSet<string> UntypedNames =
    [
        "System.Text.Json.JsonElement", "System.Text.Json.JsonDocument", "System.Text.Json.Nodes.JsonNode", "System.Text.Json.Nodes.JsonObject",
        "System.Text.Json.Nodes.JsonArray", "System.Text.Json.Nodes.JsonValue", "System.Array",
        "System.Collections.Specialized.OrderedDictionary", "System.Collections.Specialized.HybridDictionary",
        "System.Collections.Specialized.ListDictionary",
    ];

    // Non-generic collections (ArrayList, Hashtable, IEnumerable) and the dynamic types (ExpandoObject) hold objects.
    private static bool IsUntypedNamespace(ITypeSymbol type) =>
        type.ContainingNamespace?.ToDisplayString() is "System.Collections" or "System.Dynamic";

    /// <summary>What a value object may say it writes: one JSON scalar, the set <c>LeveeJson</c> holds the wire to.</summary>
    private static readonly HashSet<string> ScalarWires =
    [
        "string", "char", "bool", "byte", "sbyte", "short", "ushort", "int", "uint", "long", "ulong", "float", "double", "decimal",
        "System.Guid", "System.DateOnly", "System.TimeOnly", "System.TimeSpan", "System.DateTime", "System.DateTimeOffset", "System.Uri",
    ];

    /// <summary>A type's metadata name, as <see cref="ContractLanguage"/> names it: System.Int32, System.Collections.Generic.List`1.</summary>
    private static string MetadataName(INamedTypeSymbol type) => $"{type.ContainingNamespace.ToDisplayString()}.{type.MetadataName}";

    private const string Language = "Fix: a contract is values (strings, numbers, bool, Guid, dates and times, enums, value objects), lists and "
        + "dictionaries of them, and plain positional records, record X(A a, B b), whose members are their parameters; a choice of shapes is "
        + "an abstract record with no members whose [JsonDerivedType(typeof(X), \"x\")] subtypes are plain positional records";

    /// <summary>
    /// The path to the first type in a contract outside the contract language, with what's wrong, or null. The language is small
    /// enough that a type's schema is its parameter list: values, lists and dictionaries of them, plain positional records, and
    /// a choice of them. Whatever else C# can say about a type (a constructor, an initializer, a base, a JSON attribute) is
    /// outside it, so there's nothing for the schema and the wire to disagree about.
    /// </summary>
    private static (string Path, string Problem)? Shapeless(ITypeSymbol type, HashSet<ITypeSymbol> seen, string path, bool input, Compilation compilation)
    {
        var here = path.Length == 0 ? type.ToDisplayString() : path;
        if (!seen.Add(type))
        {
            return null;
        }
        if (type is IArrayTypeSymbol array)
        {
            return array.Rank == 1 ? Shapeless(array.ElementType, seen, path, input, compilation) : (here, $"is a many-dimensional array. Fix: an array of arrays");
        }
        if (type is not INamedTypeSymbol named)
        {
            return (here, $"is {type.ToDisplayString()}, which isn't in the contract language. {Language}");
        }
        if (named.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T)
        {
            return Shapeless(named.TypeArguments[0], seen, path, input, compilation);
        }
        var name = MetadataName(named);
        if (named.TypeKind == TypeKind.Enum || ContractLanguage.Scalars.Contains(name)
            || named.ContainingType is null && named.ContainingAssembly.Name == "Levee" && ContractLanguage.LeveeRecords.Contains(name))
        {
            return null;
        }
        if (ContractLanguage.Collections.Contains(MetadataName(named.OriginalDefinition)))
        {
            if (named.TypeArguments.Length == 2 && named.TypeArguments[0] is var key && key.TypeKind != TypeKind.Enum
                && !(key is INamedTypeSymbol keyType && ContractLanguage.Key(MetadataName(keyType))))
            {
                return (here, $"is a dictionary keyed by {key.ToDisplayString()}. Fix: key it by a string, number, Guid, date or enum");
            }
            return named.TypeArguments.Select(t => Shapeless(t, seen, path, input, compilation)).FirstOrDefault(p => p is not null);
        }
        // A value object: one scalar, written by its own converter, on its type.
        var declared = named.GetAttributes().FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == "Levee.ValueObjectAttribute");
        var converted = named.GetAttributes().Any(a => JsonAttribute(a, "JsonConverterAttribute"));
        if (declared is not null || converted)
        {
            return declared is null
                ? (here, "is written by a converter of its own, which no schema can read. Fix: say what it writes on the type, [ValueObject(typeof(string))] (with Format or Pattern if it has one)")
                : !converted
                    ? (here, "is a [ValueObject] with no converter of its own. Fix: put the converter that writes it as that scalar on the type, [JsonConverter(typeof(...))] beside [ValueObject]")
                    : declared.ConstructorArguments.FirstOrDefault().Value is ITypeSymbol wire
                        && (wire is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } nullable ? nullable.TypeArguments[0] : wire) is { TypeKind: not TypeKind.Enum } scalar
                        && !ScalarWires.Contains(scalar.ToDisplayString())
                        ? (here, $"is a value object written as {scalar.ToDisplayString()}, which isn't one JSON value. Fix: [ValueObject(typeof(string))], or a number, bool, enum, Guid or date")
                        : null;
        }
        if (named.ContainingNamespace?.ToDisplayString() is "System" || named.ContainingNamespace?.ToDisplayString().StartsWith("System.", StringComparison.Ordinal) == true
            || !named.IsRecord || named.TypeKind != TypeKind.Class)
        {
            return (here, $"is {named.ToDisplayString()}, which isn't in the contract language. {Language}");
        }
        if (!SymbolEqualityComparer.Default.Equals(named.ContainingAssembly, compilation.Assembly))
        {
            return (here, $"is {named.ContainingAssembly.Name}'s, not this contract's own. Fix: declare the contract's own record beside the operation (mapping in the handler), or carry the value as a value object or an enum");
        }
        // A choice of shapes says only which subtypes it is; anything more, the subtype says.
        var subtypes = named.GetAttributes().Where(a => JsonAttribute(a, "JsonDerivedTypeAttribute")).ToList();
        if (named.GetAttributes().FirstOrDefault(a => JsonAttribute(a) && !(named.IsAbstract && JsonAttribute(a, "JsonDerivedTypeAttribute"))) is { } attribute)
        {
            return (here, $"carries [{attribute.AttributeClass!.Name.Replace("Attribute", "")}], which changes how the wire reads it apart from what its schema says. {Language}");
        }
        if (named.IsAbstract)
        {
            if (named.BaseType?.SpecialType != SpecialType.System_Object || Declares(named) || subtypes.Count == 0
                || named.GetMembers().OfType<IPropertySymbol>().Any(p => !p.IsStatic && Seen(p))
                || subtypes.Any(d => d.ConstructorArguments.Length < 2 || !SymbolEqualityComparer.Default.Equals((d.ConstructorArguments[0].Value as INamedTypeSymbol)?.BaseType, named)))
            {
                return (here, $"isn't a choice of shapes the wire reads: an abstract record with no members and no base, each subtype deriving from it and named by a discriminator. {Language}");
            }
            return subtypes.Select(d => (ITypeSymbol)d.ConstructorArguments[0].Value!).Select(t => Shapeless(t, seen, path, input, compilation)).FirstOrDefault(p => p is not null);
        }
        if (named.BaseType is { SpecialType: not SpecialType.System_Object } baseType
            && !(baseType.IsAbstract && baseType.GetAttributes().Any(a => JsonAttribute(a, "JsonDerivedTypeAttribute") && SymbolEqualityComparer.Default.Equals(a.ConstructorArguments.FirstOrDefault().Value as ITypeSymbol, named))))
        {
            return (here, $"derives from {baseType.Name}: a record's only base is the choice of shapes that names it. {Language}");
        }
        if (Declares(named))
        {
            return (here, $"declares a member or constructor besides its parameters, which decides on its own what the wire reads or writes. {Language}");
        }
        foreach (var member in named.GetMembers().OfType<IPropertySymbol>().Where(p => !p.IsStatic && p.DeclaredAccessibility == Accessibility.Public))
        {
            var at = path.Length == 0 ? member.Name : $"{path}.{member.Name}";
            if (member.GetAttributes().FirstOrDefault(a => JsonAttribute(a) && !ContractLanguage.MemberAttributes.Contains(a.AttributeClass!.Name)) is { } onMember)
            {
                return (at, $"carries [{onMember.AttributeClass!.Name.Replace("Attribute", "")}], which changes how the wire reads it apart from what its schema says. {Language}");
            }
            if (Shapeless(member.Type, seen, at, input, compilation) is { } found)
            {
                return found;
            }
        }
        return null;
    }

    /// <summary>A System.Text.Json attribute (of the given name), or one a library derives from one.</summary>
    private static bool JsonAttribute(AttributeData attribute, string? name = null)
    {
        for (var t = attribute.AttributeClass; t is not null; t = t.BaseType)
        {
            if (t.ContainingNamespace?.ToDisplayString() == "System.Text.Json.Serialization" && (name is null || t.Name == name))
            {
                return true;
            }
        }
        return false;
    }

    /// <summary>
    /// Whether a record declares anything the wire would see besides its positional parameters: a public property or field (or
    /// one [JsonInclude] adds), or a constructor of its own. A private member, or an interface's implemented explicitly, it doesn't.
    /// </summary>
    private static bool Declares(INamedTypeSymbol record) =>
        record.GetMembers().Any(m => !m.IsStatic && m.DeclaringSyntaxReferences.Any(r => r.GetSyntax() switch
        {
            Microsoft.CodeAnalysis.CSharp.Syntax.PropertyDeclarationSyntax property => property.ExplicitInterfaceSpecifier is null && Seen(m),
            Microsoft.CodeAnalysis.CSharp.Syntax.VariableDeclaratorSyntax => m is IFieldSymbol && Seen(m),
            Microsoft.CodeAnalysis.CSharp.Syntax.ConstructorDeclarationSyntax => true,
            _ => false,
        }));

    private static bool Seen(ISymbol member) =>
        member.DeclaredAccessibility == Accessibility.Public || member.GetAttributes().Any(a => JsonAttribute(a, "JsonIncludeAttribute"));

    /// <summary>The path to the first member of an input, at any depth, typed as anything at all (object, raw JSON, dynamic), or null.</summary>
    private static string? Untyped(ITypeSymbol type, HashSet<ITypeSymbol> seen, string path)
    {
        if (type.SpecialType == SpecialType.System_Object || type.TypeKind == TypeKind.Dynamic || UntypedNames.Contains(type.OriginalDefinition.ToDisplayString())
            || IsUntypedNamespace(type))
        {
            return path.Length == 0 ? type.ToDisplayString() : path;
        }
        if (!seen.Add(type))
        {
            return null;
        }
        if (type is IArrayTypeSymbol array)
        {
            return Untyped(array.ElementType, seen, path);
        }
        if (type is not INamedTypeSymbol named)
        {
            return null;
        }
        foreach (var argument in named.TypeArguments)
        {
            if (Untyped(argument, seen, path) is { } inArgument)
            {
                return inArgument;
            }
        }
        // The BCL's own types (string, DateTimeOffset, collections) are typed; the app's are walked.
        if (named.ContainingNamespace?.ToDisplayString() is { } ns && (ns == "System" || ns.StartsWith("System.", StringComparison.Ordinal)))
        {
            return null;
        }
        // An interface's members include those it inherits.
        var declared = named.TypeKind == TypeKind.Interface ? named.AllInterfaces.Prepend(named).SelectMany(i => i.GetMembers()) : named.GetMembers();
        foreach (var member in declared)
        {
            var at = path.Length == 0 ? member.Name : $"{path}.{member.Name}";
            if (Wired(member) is { } memberType && Untyped(memberType, seen, at) is { } found)
            {
                return found;
            }
        }
        foreach (var derived in named.GetAttributes().Where(a => a.AttributeClass?.ToDisplayString() == "System.Text.Json.Serialization.JsonDerivedTypeAttribute"))
        {
            if (derived.ConstructorArguments.FirstOrDefault().Value is ITypeSymbol subtype && Untyped(subtype, seen, path) is { } inDerived)
            {
                return inDerived;
            }
        }
        if (named.BaseType is { SpecialType: not SpecialType.System_Object } baseType && Untyped(baseType, seen, path) is { } inBase)
        {
            return inBase;
        }
        // A collection of the app's own carries its items by the interface it implements (IEnumerable<object>), or none at all.
        if (named.AllInterfaces.Any(i => i.ToDisplayString() == "System.Collections.IEnumerable")
            && !named.AllInterfaces.Any(i => i.OriginalDefinition.ToDisplayString() == "System.Collections.Generic.IEnumerable<T>"))
        {
            return path.Length == 0 ? type.ToDisplayString() : path;
        }
        foreach (var contract in named.AllInterfaces.Where(i => i.ContainingNamespace?.ToDisplayString() != "Levee"))
        {
            foreach (var argument in contract.TypeArguments)
            {
                if (Untyped(argument, seen, path) is { } inContract)
                {
                    return inContract;
                }
            }
        }
        return null;
    }

    /// <summary>
    /// The member's type if System.Text.Json carries it, as its default member selection does: a public property, or a field
    /// or non-public property [JsonInclude] adds, unless [JsonIgnore] always drops it. Null for anything else.
    /// </summary>
    private static ITypeSymbol? Wired(ISymbol member)
    {
        if (member.IsStatic || member.IsImplicitlyDeclared)
        {
            return null;
        }
        var attributes = member.GetAttributes();
        // A condition other than Always (WhenWritingNull, WhenWritingDefault) still carries the member some of the time.
        if (attributes.Any(a => a.AttributeClass?.ToDisplayString() == "System.Text.Json.Serialization.JsonIgnoreAttribute"
            && a.NamedArguments.All(n => n.Key != "Condition" || n.Value.Value is 1)))
        {
            return null;
        }
        var included = attributes.Any(a => a.AttributeClass?.ToDisplayString() == "System.Text.Json.Serialization.JsonIncludeAttribute");
        return member switch
        {
            IPropertySymbol { IsIndexer: false } p when p.DeclaredAccessibility == Accessibility.Public || included => p.Type,
            IFieldSymbol f when included => f.Type,
            _ => null,
        };
    }

    private static IEnumerable<INamedTypeSymbol> Bases(INamedTypeSymbol type)
    {
        for (var t = type.BaseType; t is not null; t = t.BaseType)
        {
            yield return t;
        }
    }

    private static bool IsSecret(AttributeData attribute) => attribute.AttributeClass?.ToDisplayString() == "Levee.SecretAttribute";

    /// <summary>The path to the first [Secret] member of an input, at any depth, or null.</summary>
    private static string? SecretIn(ITypeSymbol type, HashSet<ITypeSymbol> seen, string path)
    {
        if (!seen.Add(type) || type is not INamedTypeSymbol named)
        {
            return type is IArrayTypeSymbol array ? SecretIn(array.ElementType, seen, path) : null;
        }
        foreach (var argument in named.TypeArguments)
        {
            if (SecretIn(argument, seen, path) is { } inArgument)
            {
                return inArgument;
            }
        }
        // A declared polymorphic base may arrive as any of its derived types, each on the wire as itself.
        foreach (var derived in named.GetAttributes().Where(a => a.AttributeClass?.ToDisplayString() == "System.Text.Json.Serialization.JsonDerivedTypeAttribute"))
        {
            if (derived.ConstructorArguments.FirstOrDefault().Value is ITypeSymbol subtype && SecretIn(subtype, seen, path) is { } inDerived)
            {
                return inDerived;
            }
        }
        // A collection of the app's own (a named List<Leaf>) carries its items by what it derives from and implements.
        // Only a collection's items travel: an operation's or a subscription's own result types (IOperation<T>) don't.
        foreach (var carried in Bases(named).Concat(named.AllInterfaces).Where(t => t.ContainingNamespace?.ToDisplayString() is { } ns
            && (ns == "System.Collections.Generic" || ns.StartsWith("System.Collections.", StringComparison.Ordinal))).SelectMany(t => t.TypeArguments))
        {
            if (SecretIn(carried, seen, path) is { } inItems)
            {
                return inItems;
            }
        }
        // An interface's members include those it inherits; a class's, its bases'.
        IEnumerable<INamedTypeSymbol> declaring = named.TypeKind == TypeKind.Interface ? named.AllInterfaces.Prepend(named) : Bases(named).Prepend(named);
        // The BCL's own types hold no [Secret]; their type arguments, above, may.
        foreach (var t in declaring.Where(t => t.ContainingNamespace?.ToDisplayString() is not "System" && t.ContainingNamespace?.ToDisplayString().StartsWith("System.", StringComparison.Ordinal) != true))
        {
            foreach (var member in t.GetMembers())
            {
                if (Wired(member) is not { } memberType)
                {
                    continue;
                }
                var at = path.Length == 0 ? member.Name : $"{path}.{member.Name}";
                // Marked on the member, or on the interface member it implements.
                var marked = member.GetAttributes().Any(IsSecret) || (member is IPropertySymbol property && named.AllInterfaces
                    .SelectMany(i => i.GetMembers().OfType<IPropertySymbol>())
                    .Any(i => i.GetAttributes().Any(IsSecret) && SymbolEqualityComparer.Default.Equals(named.FindImplementationForInterfaceMember(i), property)));
                if (marked)
                {
                    return at;
                }
                if (SecretIn(memberType, seen, at) is { } nested)
                {
                    return nested;
                }
            }
        }
        return null;
    }

    /// <summary>The ports <paramref name="type"/> adapts. With a context, reports a named adapter that adapts none.</summary>
    private static List<AdapterModel> Adapted(INamedTypeSymbol type, SourceProductionContext? context)
    {
        if (type.TypeKind != TypeKind.Class || type.IsAbstract || type.IsGenericType || type.DeclaredAccessibility == Accessibility.Private)
        {
            return [];
        }
        var name = Known.AdapterName(type);
        var lifetime = Known.AdapterLifetime(type);
        var ports = type.AllInterfaces.Where(Known.IsPort).Select(p => new AdapterModel(type, p, name, lifetime)).ToList();
        if (ports.Count == 0 && Known.IsNamedAdapter(type))
        {
            context?.ReportDiagnostic(Diagnostic.Create(Descriptors.OrphanAdapter, type.Locations.FirstOrDefault() ?? Location.None, type.ToDisplayString()));
        }
        return ports;
    }

    private static IEnumerable<HandlerModel> Handled(INamedTypeSymbol type)
    {
        if (type.TypeKind != TypeKind.Class || type.IsAbstract || type.IsGenericType || type.DeclaredAccessibility == Accessibility.Private)
        {
            yield break;
        }
        foreach (var i in type.AllInterfaces.Where(i => Known.Is(i, "IOperationHandler", 2) || Known.Is(i, "ISubscriptionHandler", 2)))
        {
            if (i.TypeArguments[0] is INamedTypeSymbol operation)
            {
                yield return new HandlerModel(type, operation, i.TypeArguments[1], Known.Is(i, "ISubscriptionHandler", 2));
            }
        }
    }

    /// <summary>
    /// Application's own classes its handlers and processes take, at any depth: the internal services they share (a store
    /// holding several repositories, a calculation over ports), registered as they are, scoped. A class that takes a value
    /// (a string, a number, a settings record's fields) isn't one: that's configuration, which Composition binds.
    /// </summary>
    private static List<INamedTypeSymbol> Helpers(IEnumerable<INamedTypeSymbol> roots, IAssemblySymbol assembly)
    {
        var found = new List<INamedTypeSymbol>();
        var seen = new HashSet<INamedTypeSymbol>(roots, SymbolEqualityComparer.Default);
        var pending = new Queue<INamedTypeSymbol>(seen);
        while (pending.Count > 0)
        {
            var constructor = pending.Dequeue().InstanceConstructors
                .Where(c => c.DeclaredAccessibility is not Accessibility.Private)
                .OrderByDescending(c => c.Parameters.Length)
                .FirstOrDefault();
            foreach (var parameter in constructor?.Parameters ?? [])
            {
                if (parameter.Type is INamedTypeSymbol { TypeKind: TypeKind.Class, IsAbstract: false, IsStatic: false } helper && Closed(helper)
                    && SymbolEqualityComparer.Default.Equals(helper.ContainingAssembly, assembly)
                    && Injectable(helper) && seen.Add(helper))
                {
                    found.Add(helper);
                    pending.Enqueue(helper);
                }
            }
        }
        return [.. found.OrderBy(t => t.ToDisplayString(), StringComparer.Ordinal)];
    }

    /// <summary>A type the container can construct as named: no type parameter left open in it or in a type it's nested in.</summary>
    private static bool Closed(ITypeSymbol type) => type switch
    {
        ITypeParameterSymbol => false,
        IArrayTypeSymbol array => Closed(array.ElementType),
        INamedTypeSymbol named => !named.IsUnboundGenericType && named.TypeArguments.All(Closed) && (named.ContainingType is null || Closed(named.ContainingType)),
        _ => true,
    };

    /// <summary>A class whose widest constructor takes only services (interfaces and classes), never a value.</summary>
    private static bool Injectable(INamedTypeSymbol type) =>
        type.InstanceConstructors.Where(c => c.DeclaredAccessibility is not Accessibility.Private).OrderByDescending(c => c.Parameters.Length).FirstOrDefault() is { } constructor
        && constructor.Parameters.All(p => p.Type.TypeKind is TypeKind.Interface or TypeKind.Class && p.Type.SpecialType != SpecialType.System_String);

    private static IEnumerable<(INamedTypeSymbol Process, ITypeSymbol Input)> Processed(INamedTypeSymbol type) =>
        type.TypeKind != TypeKind.Class || type.IsAbstract || type.IsGenericType || type.DeclaredAccessibility == Accessibility.Private
            ? []
            : type.AllInterfaces.Where(i => Known.Is(i, "IProcess", 1)).Select(i => (type, i.TypeArguments[0]));

    internal static IEnumerable<INamedTypeSymbol> AllTypes(INamespaceSymbol ns)
    {
        foreach (var type in ns.GetTypeMembers())
        {
            yield return type;
            foreach (var nested in Nested(type))
            {
                yield return nested;
            }
        }
        foreach (var child in ns.GetNamespaceMembers())
        {
            foreach (var type in AllTypes(child))
            {
                yield return type;
            }
        }
    }

    private static IEnumerable<INamedTypeSymbol> Nested(INamedTypeSymbol type) =>
        type.GetTypeMembers().SelectMany(t => new[] { t }.Concat(Nested(t)));

    private static string EffectsText(int effects) =>
        string.Join(" | ", new[] { (1, "Read"), (2, "Write"), (4, "External") }.Where(f => (effects & f.Item1) != 0).Select(f => f.Item2));

    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);

    private static string Identifier(string name) => new(name.Select(c => char.IsLetterOrDigit(c) ? c : '_').ToArray());

    private sealed record OperationModel(INamedTypeSymbol Type, ITypeSymbol Result, string Name, string Access, string Summary, int Effects,
        int Idempotency, bool Platform, bool Internal, bool Streams, List<string> Metadata, List<string> Errors, bool CallerScoped, bool Unscoped,
        Location Location);

    /// <summary>An attribute as the expression that makes it again: its constructor arguments, then its named ones.</summary>
    private static string Construct(AttributeData attribute)
    {
        var arguments = string.Join(", ", attribute.ConstructorArguments.Select(Value));
        var named = attribute.NamedArguments.Select(a => $"{a.Key} = {Value(a.Value)}").ToList();
        return $"new {attribute.AttributeClass!.ToDisplayString(Global)}({arguments})" + (named.Count == 0 ? "" : $" {{ {string.Join(", ", named)} }}");
    }

    private static string Value(TypedConstant constant) => constant switch
    {
        { IsNull: true } => "null",
        { Kind: TypedConstantKind.Enum } => $"({constant.Type!.ToDisplayString(Global)}){Convert.ToInt64(constant.Value, System.Globalization.CultureInfo.InvariantCulture)}",
        { Kind: TypedConstantKind.Type } => $"typeof({((ITypeSymbol)constant.Value!).ToDisplayString(Global)})",
        { Kind: TypedConstantKind.Array } => $"new {((IArrayTypeSymbol)constant.Type!).ElementType.ToDisplayString(Global)}[] {{ {string.Join(", ", constant.Values.Select(Value))} }}",
        _ => constant.ToCSharpString(),
    };

    private sealed record HandlerModel(INamedTypeSymbol Handler, INamedTypeSymbol Operation, ITypeSymbol Result, bool Streams);

    private sealed record AdapterModel(INamedTypeSymbol Adapter, INamedTypeSymbol Port, string? Name, int Lifetime);
}
